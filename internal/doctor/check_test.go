func TestCheckRequiresDatabase(t *testing.T) {
	if _, err := Check(context.Background(), nil); err == nil {
		t.Fatal("doctor must reject a missing database")
	}
}

func TestCheckDetectsDriftPostgreSQL(t *testing.T) {
	pool := database.Open(t)
	ctx := context.Background()
	if findings, err := Check(ctx, pool); err != nil || len(findings) != 0 {
		t.Fatalf("fresh migrated database: findings=%+v err=%v", findings, err)
	}
	const fixture = `
CREATE SCHEMA b_aaaaaaaaaa;
CREATE TABLE b_aaaaaaaaaa.t_bbbbbbbbbb (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(), created_by uuid,
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 c_eeeeeeeeee varchar(20), c_vvvvvvvvvv numeric(10,3));
CREATE TABLE b_aaaaaaaaaa.t_cccccccccc (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(), created_by uuid,
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by uuid,
 c_eeeeeeeeee varchar(20), c_vvvvvvvvvv numeric(10,3),
 c_dddddddddd bigint REFERENCES b_aaaaaaaaaa.t_bbbbbbbbbb(id));
CREATE TABLE b_aaaaaaaaaa.j_ffffffffff (
 parent_id bigint NOT NULL, child_id bigint NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(), created_by uuid,
 PRIMARY KEY(parent_id, child_id));
INSERT INTO meta.workspaces(name) VALUES ('doctor fixture');
INSERT INTO meta.books(workspace_id,name,pg_schema,position)
 SELECT id,'book','b_aaaaaaaaaa',1 FROM meta.workspaces WHERE name='doctor fixture';
INSERT INTO meta.tables(book_id,name,pg_name,position)
 SELECT id,'parent','t_bbbbbbbbbb',1 FROM meta.books WHERE pg_schema='b_aaaaaaaaaa';
INSERT INTO meta.tables(book_id,name,pg_name,position,deleted_at)
 SELECT id,'child','t_cccccccccc',2,now() FROM meta.books WHERE pg_schema='b_aaaaaaaaaa';
INSERT INTO meta.fields(table_id,name,ui_type,pg_column,pg_type,position)
 SELECT t.id, v.name, v.kind, v.col, v.typ, v.pos
 FROM meta.tables t CROSS JOIN (VALUES
 ('ID','id','id','bigint',1), ('Created','created_at','created_at','timestamptz',2),
 ('Creator','created_by','created_by','uuid',3), ('Updated','updated_at','updated_at','timestamptz',4),
 ('Updater','updated_by','updated_by','uuid',5), ('Text','text','c_eeeeeeeeee','varchar(20)',6),
 ('Number','decimal','c_vvvvvvvvvv','numeric(10,3)',7),
 ('Link','link',NULL,NULL,8), ('Many','link',NULL,NULL,9),
 ('Computed','formula',NULL,NULL,10)
 ) AS v(name,kind,col,typ,pos)
 WHERE t.pg_name IN ('t_bbbbbbbbbb','t_cccccccccc');
UPDATE meta.fields SET deleted_at=now() WHERE name='Text';
INSERT INTO meta.relations(book_id,kind,parent_table_id,child_table_id,parent_field_id,child_field_id,fk_column)
 SELECT b.id,'one_many',p.id,c.id,pf.id,cf.id,'c_dddddddddd'
 FROM meta.books b JOIN meta.tables p ON p.book_id=b.id AND p.pg_name='t_bbbbbbbbbb'
 JOIN meta.tables c ON c.book_id=b.id AND c.pg_name='t_cccccccccc'
 JOIN meta.fields pf ON pf.table_id=p.id AND pf.name='Link'
 JOIN meta.fields cf ON cf.table_id=c.id AND cf.name='Link'
 WHERE b.pg_schema='b_aaaaaaaaaa';
INSERT INTO meta.relations(book_id,kind,parent_table_id,child_table_id,parent_field_id,child_field_id,junction_table)
 SELECT b.id,'many_many',p.id,c.id,pf.id,cf.id,'j_ffffffffff'
 FROM meta.books b JOIN meta.tables p ON p.book_id=b.id AND p.pg_name='t_bbbbbbbbbb'
 JOIN meta.tables c ON c.book_id=b.id AND c.pg_name='t_cccccccccc'
 JOIN meta.fields pf ON pf.table_id=p.id AND pf.name='Many'
 JOIN meta.fields cf ON cf.table_id=c.id AND cf.name='Many'
 WHERE b.pg_schema='b_aaaaaaaaaa';`
	if _, err := pool.Exec(ctx, fixture); err != nil {
		t.Fatal(err)
	}
	if findings, err := Check(ctx, pool); err != nil || len(findings) != 0 {
		t.Fatalf("valid stored, virtual, trashed and relation objects: findings=%+v err=%v", findings, err)
	}
	const breakFixture = `
ALTER TABLE b_aaaaaaaaaa.t_bbbbbbbbbb DROP COLUMN c_eeeeeeeeee;
ALTER TABLE b_aaaaaaaaaa.t_bbbbbbbbbb ALTER COLUMN c_vvvvvvvvvv TYPE numeric(10,4);
ALTER TABLE b_aaaaaaaaaa.t_bbbbbbbbbb ADD COLUMN unregistered text;
ALTER TABLE b_aaaaaaaaaa.t_cccccccccc DROP COLUMN c_dddddddddd;
DROP TABLE b_aaaaaaaaaa.j_ffffffffff;
CREATE TABLE b_aaaaaaaaaa.unregistered (id bigint);
CREATE SCHEMA b_zzzzzzzzzz;
UPDATE meta.fields SET pg_type='text' WHERE name='Computed' AND table_id=
 (SELECT id FROM meta.tables WHERE pg_name='t_bbbbbbbbbb');
UPDATE public.goose_db_version SET is_applied=false WHERE version_id=5;`
	if _, err := pool.Exec(ctx, breakFixture); err != nil {
		t.Fatal(err)
	}
	findings, err := Check(ctx, pool)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []struct{ kind, object string }{
		{"migration", "5"}, {"missing_column", "c_eeeeeeeeee"},
		{"column_type", "c_vvvvvvvvvv"}, {"unexpected_column", "unregistered"},
		{"missing_column", "c_dddddddddd"}, {"missing_table", "j_ffffffffff"},
		{"unexpected_table", "unregistered"}, {"unexpected_schema", "b_zzzzzzzzzz"},
		{"field_metadata", "t_bbbbbbbbbb"},
	} {
		found := false
		for _, finding := range findings {
			if finding.Kind == want.kind && strings.Contains(finding.Object, want.object) {
				found = true
				break
			}
		}
		if !found {
			t.Errorf("missing finding %s %s: %+v", want.kind, want.object, findings)
		}
	}
	if _, err := pool.Exec(ctx, `ALTER TABLE meta.fields RENAME TO fields_temporarily_unavailable`); err != nil {
		t.Fatal(err)
	}
	if _, err := Check(ctx, pool); err == nil {
		t.Error("unavailable metadata must fail, not report a successful check")
	}
	if _, err := pool.Exec(ctx, `ALTER TABLE meta.fields_temporarily_unavailable RENAME TO fields`); err != nil {
		t.Fatal(err)
	}
	canceled, cancel := context.WithCancel(ctx)
	cancel()
	if _, err := Check(canceled, pool); err == nil {
		t.Error("canceled check must fail")
	}
}
