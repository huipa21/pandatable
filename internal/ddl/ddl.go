package ddl

import (
	"context"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"

	"pandatable/internal/apperr"
)

var ErrIdentifierCollision = errors.New("physical identifier collision")

type TableName struct {
	Schema string
	Name   string
}

func (table TableName) sql() (string, error) {
	if err := ValidateIdentifier(Book, table.Schema); err != nil {
		return "", err
	}
	if err := ValidateIdentifier(Table, table.Name); err != nil {
		return "", err
	}
	return pgx.Identifier{table.Schema, table.Name}.Sanitize(), nil
}

type ColumnSpec struct {
	Name       string
	Type       DataType
	NotNull    bool
	Unique     bool
	Default    DefaultValue
	RangeCheck *IntRangeCheck
	Reference  Reference
}

type IntRangeCheck struct {
	Min int64
	Max int64
}

type Reference string

const (
	NoReference   Reference = ""
	UserReference Reference = "user"
)

func CreateSchema(ctx context.Context, tx pgx.Tx, name string) error {
	if err := ValidateIdentifier(Book, name); err != nil {
		return err
	}
	return execute(ctx, tx, "create schema", "CREATE SCHEMA "+pgx.Identifier{name}.Sanitize(), true)
}

func CreateTable(ctx context.Context, tx pgx.Tx, table TableName) error {
	name, err := table.sql()
	if err != nil {
		return err
	}
	return execute(ctx, tx, "create table", "CREATE TABLE "+name+` (
		"id" pg_catalog.int8 GENERATED BY DEFAULT AS IDENTITY CONSTRAINT `+pgx.Identifier{table.Name + "_pkey"}.Sanitize()+` PRIMARY KEY,
		"created_at" pg_catalog.timestamptz NOT NULL DEFAULT pg_catalog.now(),
		"created_by" pg_catalog.uuid,
		"updated_at" pg_catalog.timestamptz NOT NULL DEFAULT pg_catalog.now(),
		"updated_by" pg_catalog.uuid
	)`, true)
}

func AddColumn(ctx context.Context, tx pgx.Tx, table TableName, column ColumnSpec) error {
	name, err := columnTarget(table, column.Name)
	if err != nil {
		return err
	}
	typeSQL, err := column.Type.SQL()
	if err != nil {
		return err
	}
	defaultSQL, err := column.Default.sql(column.Type)
	if err != nil {
		return err
	}
	query := "ALTER TABLE " + name + " ADD COLUMN " + pgx.Identifier{column.Name}.Sanitize() + " " + typeSQL
	if defaultSQL != "" {
		query += " DEFAULT " + defaultSQL
	}
	if column.NotNull {
		query += " NOT NULL"
	}
	if column.Unique {
		query += " CONSTRAINT " + uniqueName(table, column.Name) + " UNIQUE"
	}
	if column.RangeCheck != nil {
		if column.Type.Kind != SmallInt || column.RangeCheck.Min > column.RangeCheck.Max ||
			column.RangeCheck.Min < -32768 || column.RangeCheck.Max > 32767 {
			return validation("Invalid integer range check")
		}
		query += " CONSTRAINT " + rangeName(table, column.Name) + " CHECK (" +
			pgx.Identifier{column.Name}.Sanitize() + " BETWEEN " +
			fmt.Sprintf("%d AND %d", column.RangeCheck.Min, column.RangeCheck.Max) + ")"
	}
	switch column.Reference {
	case NoReference:
	case UserReference:
		if column.Type.Kind != UUID || column.NotNull {
			return validation("Invalid user reference")
		}
		query += " CONSTRAINT " + foreignKeyName(table, column.Name) + " REFERENCES meta.users(id) ON DELETE SET NULL"
	default:
		return validation("Invalid column reference")
	}
	return execute(ctx, tx, "add column", query, true)
}

// AddAutoNumberColumn creates a per-column sequence, numbers existing rows in
// ascending id order, and installs it as the column default. The sequence is
// owned by the column, so a purge DROP COLUMN removes it atomically.
func AddAutoNumberColumn(ctx context.Context, tx pgx.Tx, table TableName, column string) error {
	name, err := columnTarget(table, column)
	if err != nil {
		return err
	}
	sequence, err := sequenceForColumn(column)
	if err != nil {
		return err
	}
	seqName := pgx.Identifier{table.Schema, sequence}.Sanitize()
	quotedColumn := pgx.Identifier{column}.Sanitize()
	if err := execute(ctx, tx, "create autonumber sequence", "CREATE SEQUENCE "+seqName, true); err != nil {
		return err
	}
	if err := execute(ctx, tx, "add autonumber column", "ALTER TABLE "+name+" ADD COLUMN "+quotedColumn+" pg_catalog.int8", true); err != nil {
		return err
	}
	nextValue := "pg_catalog.nextval('" + table.Schema + "." + sequence + "'::pg_catalog.regclass)"
	backfill := "WITH numbered AS MATERIALIZED (SELECT \"id\", " + nextValue +
		" AS value FROM " + name + " ORDER BY \"id\") UPDATE " + name +
		" AS target SET " + quotedColumn + " = numbered.value FROM numbered WHERE target.\"id\" = numbered.\"id\""
	if err := execute(ctx, tx, "backfill autonumber column", backfill, false); err != nil {
		return err
	}
	if err := execute(ctx, tx, "set autonumber default",
		"ALTER TABLE "+name+" ALTER COLUMN "+quotedColumn+" SET DEFAULT "+nextValue, false); err != nil {
		return err
	}
	if err := execute(ctx, tx, "own autonumber sequence",
		"ALTER SEQUENCE "+seqName+" OWNED BY "+name+"."+quotedColumn, false); err != nil {
		return err
	}
	return execute(ctx, tx, "require autonumber value",
		"ALTER TABLE "+name+" ALTER COLUMN "+quotedColumn+" SET NOT NULL", false)
}

func sequenceForColumn(column string) (string, error) {
	if err := ValidateIdentifier(Column, column); err != nil {
		return "", err
	}
	return "s_" + column[2:], nil
}

func DropColumn(ctx context.Context, tx pgx.Tx, table TableName, column string) error {
	return alterColumn(ctx, tx, table, column, "drop column", "DROP COLUMN", "")
}

func SetNotNull(ctx context.Context, tx pgx.Tx, table TableName, column string, required bool) error {
	action := "DROP NOT NULL"
	if required {
		action = "SET NOT NULL"
	}
	return alterColumn(ctx, tx, table, column, "set not null", "ALTER COLUMN", " "+action)
}

// AddUnique removes the module's named constraint when enabled is false.
// NULLs remain distinct; this is not an index/background-job API.
func AddUnique(ctx context.Context, tx pgx.Tx, table TableName, column string, enabled bool) error {
	name, err := columnTarget(table, column)
	if err != nil {
		return err
	}
	action := " DROP CONSTRAINT " + uniqueName(table, column)
	if enabled {
		action = " ADD CONSTRAINT " + uniqueName(table, column) + " UNIQUE (" + pgx.Identifier{column}.Sanitize() + ")"
	}
	return execute(ctx, tx, "set unique", "ALTER TABLE "+name+action, false)
}

func SetDefault(ctx context.Context, tx pgx.Tx, table TableName, column string, dataType DataType, value DefaultValue) error {
	if _, err := columnTarget(table, column); err != nil {
		return err
	}
	expression, err := value.sql(dataType)
	if err != nil {
		return err
	}
	action := " DROP DEFAULT"
	if expression != "" {
		action = " SET DEFAULT " + expression
	}
	return alterColumn(ctx, tx, table, column, "set default", "ALTER COLUMN", action)
}

func alterColumn(ctx context.Context, tx pgx.Tx, table TableName, column, operation, action, suffix string) error {
	name, err := columnTarget(table, column)
	if err != nil {
		return err
	}
	return execute(ctx, tx, operation, "ALTER TABLE "+name+" "+action+" "+pgx.Identifier{column}.Sanitize()+suffix, false)
}

func columnTarget(table TableName, column string) (string, error) {
	if err := ValidateIdentifier(Column, column); err != nil {
		return "", err
	}
	return table.sql()
}

func uniqueName(table TableName, column string) string {
	return pgx.Identifier{table.Name + "_" + column + "_key"}.Sanitize()
}

func rangeName(table TableName, column string) string {
	return pgx.Identifier{table.Name + "_" + column + "_check"}.Sanitize()
}

func foreignKeyName(table TableName, column string) string {
	return pgx.Identifier{table.Name + "_" + column + "_fkey"}.Sanitize()
}

func execute(ctx context.Context, tx pgx.Tx, operation, query string, creating bool) error {
	if tx == nil {
		return validation("DDL requires a caller transaction")
	}
	if _, err := tx.Exec(ctx, "SET LOCAL lock_timeout = '3s'"); err != nil {
		return fmt.Errorf("ddl %s lock timeout: %w", operation, err)
	}
	if _, err := tx.Exec(ctx, query); err != nil {
		return fmt.Errorf("ddl %s: %w", operation, databaseError(err, creating))
	}
	return nil
}

func validation(message string) error {
	return apperr.New(400, "ERR_VALIDATION", message)
}

func databaseError(err error, creating bool) error {
	var postgres *pgconn.PgError
	if !errors.As(err, &postgres) {
		return err
	}
	switch {
	case creating && (postgres.Code == "42P06" || postgres.Code == "42P07" || postgres.Code == "42701"):
		return errors.Join(ErrIdentifierCollision, apperr.New(409, "ERR_DDL_CONFLICT", "Physical identifier is already reserved"))
	case postgres.Code == "23502" || postgres.Code == "23505" || postgres.Code == "42710" ||
		postgres.Code == "42P06" || postgres.Code == "42P07" || postgres.Code == "42701":
		return apperr.New(409, "ERR_DDL_CONFLICT", "Existing data or constraints conflict with this schema change")
	case postgres.Code == "55P03":
		return apperr.New(409, "ERR_DDL_LOCK_TIMEOUT", "Schema is busy; retry the transaction later")
	case len(postgres.Code) == 5 && postgres.Code[:2] == "22":
		return validation("Default value is invalid for the column type")
	default:
		return err
	}
}
